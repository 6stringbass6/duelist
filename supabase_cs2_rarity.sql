alter table public.skin_catalog drop constraint if exists skin_catalog_rarity_check;
-- 1) 컬렉션별 재배정 (client/src/config/skins.ts 와 동일)
update public.skin_catalog set rarity = case split_part(skin_id, '_', 1)
  when 'matte' then 'consumer' when 'digicamo' then 'industrial' when 'steel' then 'milspec' when 'racing' then 'milspec'
  when 'anodized' then 'restricted' when 'hexarmor' then 'restricted' when 'gloss' then 'restricted'
  when 'circuit' then 'classified' when 'glitch' then 'classified'
  when 'flux' then 'covert' when 'aurora' then 'covert' when 'solar' then 'covert' when 'abyss' then 'covert'
  when 'karambit' then 'exrare' when 'butterfly' then 'exrare' when 'skeleton' then 'exrare'
  else rarity end;
-- 2) 남은 구버전 키 안전 매핑
update public.skin_catalog set rarity = case rarity
  when 'common' then 'consumer' when 'uncommon' then 'industrial' when 'rare' then 'milspec' when 'epic' then 'classified'
  when 'legendary' then 'covert' when 'mythic' then 'covert'
  when 'select' then 'consumer' when 'deluxe' then 'milspec' when 'premium' then 'classified' when 'exclusive' then 'covert' when 'ultra' then 'covert'
  else rarity end
where rarity in ('common','uncommon','rare','epic','legendary','mythic','select','deluxe','premium','exclusive','ultra');
alter table public.skin_catalog add constraint skin_catalog_rarity_check
  check (rarity in ('default','consumer','industrial','milspec','restricted','classified','covert','exrare','contraband'));
